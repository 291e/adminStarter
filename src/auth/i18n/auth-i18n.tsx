const AuthLocaleContext = createContext<AuthLocaleContextValue | null>(null);

const getInitialLocale = (): Locale => {
  if (typeof window === 'undefined') {
    return 'ko';
  }
  const stored = localStorage.getItem(AUTH_LOCALE_KEY) as Locale | null;
  const exists = LOCALE_OPTIONS.find((option) => option.value === stored);
  return exists ? stored! : 'ko';
};

export function AuthLocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      localStorage.setItem(AUTH_LOCALE_KEY, locale);
    }
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: string) => {
      const table = TRANSLATIONS[locale] || TRANSLATIONS.ko;
      return table[key] || TRANSLATIONS.en[key] || key;
    },
    [locale]
  );

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t,
      options: LOCALE_OPTIONS,
    }),
    [locale, setLocale, t]
  );

  return <AuthLocaleContext.Provider value={value}>{children}</AuthLocaleContext.Provider>;
}

export function useAuthI18n() {
  const context = useContext(AuthLocaleContext);
  if (!context) {
    throw new Error('useAuthI18n must be used within AuthLocaleProvider');
  }
  return context;
}
